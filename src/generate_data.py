"""Create a SYNTHETIC churn dataset (7,000 customers) for development and demos.

The labels come from a made-up formula plus random noise, so results on this data show that the
pipeline works. They do NOT describe real customers. For real results, use real data:
see src/prepare_telco.py.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import numpy as np
import pandas as pd

from src.config import DATA_CARD_PATH, DATA_PATH, RANDOM_STATE

N = 7000
TARGET_CHURN_RATE = 0.265   # real telecom datasets are imbalanced like this


def generate(n: int = N, seed: int = RANDOM_STATE) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    pick = lambda values, p=None: rng.choice(values, n, p=p)

    contract = pick(["Month-to-month", "One year", "Two year"], [0.55, 0.21, 0.24])
    internet = pick(["DSL", "Fiber optic", "No"], [0.34, 0.44, 0.22])
    has_net = internet != "No"
    online_sec = np.where(has_net & (rng.random(n) < 0.30), "Yes", "No")
    tech = np.where(has_net & (rng.random(n) < 0.30), "Yes", "No")

    tenure = np.where(contract == "Month-to-month", rng.gamma(1.6, 10, n),
             np.where(contract == "One year", rng.normal(34, 16, n), rng.normal(46, 16, n)))
    tenure = np.clip(tenure, 0, 72).astype(int)

    base = np.select([internet == "No", internet == "DSL"], [20, 48], default=82)
    charges = base + rng.normal(0, 9, n) + 6 * (online_sec == "Yes") + 5 * (tech == "Yes")
    charges = np.round(np.clip(charges, 18, 120), 2)

    df = pd.DataFrame({
        "customer_id": [f"C{i:05d}" for i in range(1, n + 1)],
        "gender": pick(["Female", "Male"]),
        "senior_citizen": (rng.random(n) < 0.16).astype(int),
        "partner": pick(["No", "Yes"], [0.52, 0.48]),
        "dependents": pick(["No", "Yes"], [0.70, 0.30]),
        "tenure": tenure,
        "internet_service": internet,
        "online_security": online_sec,
        "tech_support": tech,
        "contract": contract,
        "paperless_billing": pick(["No", "Yes"], [0.41, 0.59]),
        "payment_method": pick(["Electronic check", "Mailed check",
                                "Bank transfer (automatic)", "Credit card (automatic)"],
                               [0.34, 0.23, 0.22, 0.21]),
        "monthly_charges": charges,
    })

    # churn probability: gender has NO effect on purpose
    z = (np.select([contract == "One year", contract == "Two year"], [-1.0, -1.9], default=0.0)
         + np.select([internet == "Fiber optic", internet == "No"], [0.6, -0.9], default=0.0)
         - 0.035 * tenure + 0.012 * (charges - 65)
         - 0.5 * (online_sec == "Yes") - 0.5 * (tech == "Yes")
         + 0.3 * (df.paperless_billing == "Yes") + 0.6 * (df.payment_method == "Electronic check")
         + 0.3 * df.senior_citizen - 0.2 * (df.partner == "Yes") - 0.25 * (df.dependents == "Yes"))
    lo, hi = -10.0, 10.0                      # find the intercept that gives the target churn rate
    for _ in range(60):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if (1 / (1 + np.exp(-(z + mid)))).mean() < TARGET_CHURN_RATE else (lo, mid)
    p = 1 / (1 + np.exp(-(z + (lo + hi) / 2)))
    df["churn"] = np.where(rng.random(n) < p, "Yes", "No")

    # a few missing values, as in real data
    df.loc[rng.random(n) < 0.005, "monthly_charges"] = np.nan
    return df


if __name__ == "__main__":
    data = generate()
    DATA_PATH.parent.mkdir(exist_ok=True)
    data.to_csv(DATA_PATH, index=False)
    DATA_CARD_PATH.write_text(json.dumps({
        "source": "Synthetic data generated by src/generate_data.py",
        "is_real": False,
        "rows": len(data),
    }, indent=2))
    print(f"Saved {len(data)} rows to {DATA_PATH}")
    print(f"Churn rate: {(data.churn == 'Yes').mean():.1%}")
